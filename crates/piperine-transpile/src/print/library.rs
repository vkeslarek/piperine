//! `LibraryPrinter`: a design as one Rust source text, `design.rs` (design "What the generated
//! source looks like").
//!
//! The file holds a header, `pub mod rt;` (the runtime source), the imports the text names and
//! nothing more, every IR function a running body reaches (`ValuePrinter::function`), one `pub
//! mod` per body that runs, and `piperine_abi_1`. A body's module holds one unit struct; its
//! `impl` holds the shape (the plan's, printed by `ShapePrinter`, built once) and one Rust
//! function per function of the shape (`AnalogPrinter`); its `Device` impl gives every instance
//! that shape (no M1 param is structural), runs function `k` through a `match` with one commented
//! arm per function, and has no reaction. `piperine_abi_1` returns the library of the modules,
//! built once, in body order; each module keeps its body's MSL name as its ABI name.
//!
//! Exporting the symbol takes `#[unsafe(no_mangle)]` in edition 2024: an attribute, no `unsafe`
//! block; every unsafe operation stays in the ABI crate's thunks.

use std::collections::BTreeSet;

use piperine_ir::{Expr, ExprId, FunctionId, Ir, Stmt};
use piperine_plan::{BodyPlan, Mode};

use crate::Error;
use crate::print::{AnalogPrinter, ShapePrinter, Text, ValuePrinter};

/// Prints a design.
#[derive(Debug)]
pub struct LibraryPrinter;

impl LibraryPrinter {
    /// The digital forms have no lowering yet (ir-rust phases 6 and 7): a body that holds one is
    /// `Error::Unsupported`, never printed without it.
    fn discrete(ir: &Ir) -> Result<(), Error> {
        for body in ir.bodies() {
            let first = body
                .carriers()
                .first()
                .map(|c| ("a discrete carrier", format!("body {} carrier {}", body.name(), c.name), c.origin.clone()))
                .or_else(|| body.drives().first().map(|d| ("a drive", format!("body {} drive {}", body.name(), d.carrier), d.origin.clone())))
                .or_else(|| body.events().first().map(|e| ("an event", format!("body {} event 0", body.name()), e.origin.clone())))
                .or_else(|| body.reactions().first().map(|r| ("a reaction", format!("body {} reaction 0", body.name()), r.origin.clone())));
            if let Some((form, path, origin)) = first {
                return Err(Error::Unsupported { form: form.to_string(), path, origin });
            }
        }
        Ok(())
    }

    /// `ir` as one Rust source text; `plans` holds one entry per body, `None` for a body with
    /// nothing to run.
    pub fn design(ir: &Ir, plans: &[Option<BodyPlan>]) -> Result<String, Error> {
        Self::discrete(ir)?;
        let top = ir.top();
        let design = top.body().name();
        let at = top.body().origin().clone();
        let running: Vec<(piperine_ir::Body<'_>, &BodyPlan)> =
            ir.bodies().filter_map(|b| plans.get(b.id().index()).and_then(Option::as_ref).map(|p| (b, p))).collect();

        let mut uses: BTreeSet<&'static str> = BTreeSet::new();
        let mut shapes = ShapePrinter::new();

        // The IR functions the running bodies reach, in arena order.
        let functions = Self::reached(ir, &running);
        let mut function_texts = Vec::new();
        for f in &functions {
            function_texts.push(ValuePrinter::function(ir, *f)?);
        }
        if !functions.is_empty() {
            uses.insert("rt::Real");
        }

        // One module per running body.
        let mut modules = Vec::new();
        let mut taken = BTreeSet::new();
        for (body, plan) in &running {
            let snake = Self::snake(body.name());
            let mut module = Text::ident(&snake);
            if !taken.insert(module.clone()) {
                module = Text::generated(&format!("{snake}_{}", body.id().index()));
                taken.insert(module.clone());
            }
            let strukt = Text::ident(&Self::camel(body.name()));
            let text = Self::body(body, plan, &module, &strukt, &mut shapes, &mut uses)?;
            modules.push((body.name(), module, strukt, text));
        }
        uses.extend(shapes.uses().iter().copied());
        for path in ["piperine_abi::raw::Library", "piperine_abi::raw::Module", "piperine_abi::thunk::library", "std::sync::OnceLock"] {
            uses.insert(path);
        }
        if !modules.is_empty() {
            uses.insert("piperine_abi::thunk::module");
        }

        let mut t = Text::new();
        t.line(&format!("// design {design}, generated by piperine-transpile. Do not edit: edit the model."));
        t.comment(&format!("design {design}: the runtime types `Real` and `Dual` (rt.rs)"), &at);
        t.line("pub mod rt;");
        t.line("");
        for line in Self::imports(&uses) {
            t.line(&line);
        }
        for text in &function_texts {
            t.line("");
            t.line(text.trim_end());
        }
        for (_, _, _, text) in &modules {
            t.line("");
            t.line(text);
        }
        t.line("");
        t.comment(&format!("design {design}: the library, one module per body that runs, in body order"), &at);
        t.line("#[unsafe(no_mangle)]");
        t.line("pub extern \"C\" fn piperine_abi_1() -> *const Library {");
        t.indented(|t| {
            t.line(&format!("static MODULES: OnceLock<[Module; {}]> = OnceLock::new();", modules.len()));
            t.line("static LIBRARY: OnceLock<Library> = OnceLock::new();");
            if modules.is_empty() {
                t.line("let modules = MODULES.get_or_init(|| []);");
            } else {
                t.line("let modules = MODULES.get_or_init(|| {");
                t.indented(|t| {
                    t.line("[");
                    t.indented(|t| {
                        for (name, module, strukt, _) in &modules {
                            t.line(&format!("module::<{module}::{strukt}>({name:?}),"));
                        }
                    });
                    t.line("]");
                });
                t.line("});");
            }
            t.line(&format!("LIBRARY.get_or_init(|| library({design:?}, \"piperine-transpile\", modules))"));
        });
        t.line("}");
        Ok(t.finish())
    }

    /// The `pub mod` of one body.
    fn body(
        body: &piperine_ir::Body<'_>,
        plan: &BodyPlan,
        module: &str,
        strukt: &str,
        shapes: &mut ShapePrinter,
        uses: &mut BTreeSet<&'static str>,
    ) -> Result<String, Error> {
        let name = body.name();
        let at = body.origin();
        let analog = AnalogPrinter::new(*body, plan);
        let mut functions = Vec::new();
        let mut arms = Vec::new();
        for (k, f) in plan.functions().iter().enumerate() {
            let (text, call) = match f.mode {
                Mode::Terms => (analog.terms(k)?, "terms".to_string()),
                Mode::Limit(s) => (analog.limit(k)?, format!("{}_limit", Self::site(body.limits(), s))),
                Mode::Stim(s) => (analog.stim(k)?, format!("{}_stim", Self::site(body.stims(), s))),
                Mode::Check(p) => {
                    uses.insert("piperine_abi::layout::HIGH");
                    uses.insert("piperine_abi::layout::LOW");
                    let param = body.params().get(p as usize).map_or_else(|| p.to_string(), |x| x.name.clone());
                    (analog.check(k)?, format!("{param}_check"))
                }
                // `discrete` refused every body that has a digital function before any printing.
                Mode::Cross(_) | Mode::Drive(_) | Mode::Event(_) | Mode::DelayedEvent(_) => {
                    return Err(Error::Unsupported { form: format!("the digital function {:?}", f.mode), path: format!("body {name} function {k}"), origin: at.clone() });
                }
            };
            if matches!(f.mode, Mode::Terms | Mode::Limit(_)) {
                uses.insert("rt::Dual");
            }
            uses.insert("rt::Real");
            uses.insert("piperine_abi::device::Eval");
            functions.push(text);
            let shape = plan.shape().shape();
            let entry = shape.functions.get(k);
            let (fname, origin) = entry.map_or(("", ""), |e| (e.name.as_str(), e.origin.as_str()));
            arms.push(format!("// function {k} `{fname}` @ {origin}\n{k} => Self::{call}(cx),"));
        }
        for path in [
            "piperine_abi::device::Device",
            "piperine_abi::device::Fault",
            "piperine_abi::device::Flow",
            "piperine_abi::device::React",
            "piperine_abi::device::Values",
            "piperine_abi::raw::Shape",
            "piperine_abi::shape::ShapeRef",
            "std::sync::Arc",
            "std::sync::OnceLock",
        ] {
            uses.insert(path);
        }
        let shape = shapes.prototype(plan.shape().shape());

        let mut t = Text::new();
        t.comment(&format!("body {name}"), at);
        t.line(&format!("pub mod {module} {{"));
        t.indented(|t| {
            t.line("use super::*;");
            t.line("");
            t.line(&format!("pub struct {strukt};"));
            t.line("");
            t.line(&format!("impl {strukt} {{"));
            t.indented(|t| {
                t.comment(&format!("body {name}: the shape every instance gets, built once"), at);
                t.line("fn shape() -> &'static ShapeRef {");
                t.indented(|t| {
                    t.line("static SHAPE: OnceLock<ShapeRef> = OnceLock::new();");
                    t.line("SHAPE.get_or_init(|| {");
                    t.indented(|t| t.line(&shape));
                    t.line("})");
                });
                t.line("}");
                for f in &functions {
                    t.line("");
                    t.line(f);
                }
            });
            t.line("}");
            t.line("");
            t.line(&format!("impl Device for {strukt} {{"));
            t.indented(|t| {
                t.comment(&format!("body {name}: the shape at default values"), at);
                t.line("fn prototype() -> &'static Shape<'static> {");
                t.indented(|t| t.line("Self::shape().shape()"));
                t.line("}");
                t.line("");
                t.comment(&format!("body {name}: every instance gets the one shape; no param is structural"), at);
                t.line("fn create(_values: &Values<'_>) -> Result<(Self, ShapeRef), Fault> {");
                t.indented(|t| t.line(&format!("Ok(({strukt}, Arc::clone(Self::shape())))")));
                t.line("}");
                t.line("");
                t.comment(&format!("body {name}: function `k` of the shape"), at);
                let cx = if arms.is_empty() { "_cx" } else { "cx" };
                t.line(&format!("fn eval(&self, k: u32, {cx}: &mut Eval<'_>) -> Result<(), Fault> {{"));
                t.indented(|t| {
                    t.line("match k {");
                    t.indented(|t| {
                        for arm in &arms {
                            t.line(arm);
                        }
                        t.line(&format!("_ => Err(Fault::new(2, format!(\"{name}: function {{k}} does not exist\"))),"));
                    });
                    t.line("}");
                });
                t.line("}");
                t.line("");
                t.comment(&format!("body {name}: it has no reaction"), at);
                t.line("fn react(&self, k: u32, _cx: &mut React<'_>) -> Result<Flow, Fault> {");
                t.indented(|t| t.line(&format!("Err(Fault::new(2, format!(\"{name}: reaction {{k}} does not exist\")))")));
                t.line("}");
            });
            t.line("}");
        });
        t.line("}");
        uses.insert("piperine_abi::device::Eval");
        let mut text = t.finish();
        text.pop();
        Ok(text)
    }

    fn site(sites: &[piperine_ir::Site], k: u32) -> String {
        sites.get(k as usize).map_or_else(|| format!("site{k}"), |s| s.name.clone())
    }

    /// The IR functions the running bodies call, directly or through other functions, in arena
    /// order.
    fn reached(ir: &Ir, running: &[(piperine_ir::Body<'_>, &BodyPlan)]) -> Vec<FunctionId> {
        let mut exprs: Vec<ExprId> = Vec::new();
        for (body, _) in running {
            for s in body.analog().unwrap_or(&[]) {
                match ir.stmt(*s) {
                    Stmt::Let { init, .. } => exprs.push(*init),
                    Stmt::Expr(e) => exprs.push(*e),
                    Stmt::Contribute { addends, .. } => exprs.extend(addends.iter().map(|a| a.value)),
                    Stmt::Commit { value, after, .. } => exprs.extend([*value].into_iter().chain(*after)),
                }
            }
            exprs.extend(body.params().iter().filter_map(|p| p.check));
        }
        let mut found = BTreeSet::new();
        while let Some(e) = exprs.pop() {
            match ir.expr(e) {
                Expr::Call { function, args } => {
                    if found.insert(function.index()) {
                        exprs.push(ir.function(*function).body());
                    }
                    exprs.extend(args);
                }
                other => ValuePrinter::children(ir, other, &mut exprs),
            }
        }
        ir.functions().filter(|f| found.contains(&f.id().index())).map(|f| f.id()).collect()
    }

    /// The `use` lines of `uses`, one per module path, names sorted.
    fn imports(uses: &BTreeSet<&'static str>) -> Vec<String> {
        let mut by_module: Vec<(String, Vec<String>)> = Vec::new();
        for path in uses {
            let (module, name) = path.rsplit_once("::").unwrap_or(("", path));
            match by_module.iter_mut().find(|(m, _)| m == module) {
                Some((_, names)) => names.push(name.to_string()),
                None => by_module.push((module.to_string(), vec![name.to_string()])),
            }
        }
        by_module
            .into_iter()
            .map(|(module, names)| {
                if names.len() == 1 { format!("use {module}::{};", names[0]) } else { format!("use {module}::{{{}}};", names.join(", ")) }
            })
            .collect()
    }

    /// `DiodeIv` as `diode_iv`: a module name.
    fn snake(name: &str) -> String {
        let mut out = String::new();
        let mut previous_lower = false;
        for c in name.chars() {
            if c.is_ascii_uppercase() {
                if previous_lower {
                    out.push('_');
                }
                out.push(c.to_ascii_lowercase());
                previous_lower = false;
            } else {
                out.push(c);
                previous_lower = c.is_ascii_lowercase() || c.is_ascii_digit();
            }
        }
        out
    }

    /// `white_noise` as `WhiteNoise`: a type name; a name already in camel case is unchanged.
    fn camel(name: &str) -> String {
        let mut out = String::new();
        let mut upper = true;
        for c in name.chars() {
            if c == '_' {
                upper = true;
            } else if upper {
                out.push(c.to_ascii_uppercase());
                upper = false;
            } else {
                out.push(c);
            }
        }
        out
    }
}
